/**
 * Generates the BrudOS kernel API catalogue from the kernel's own runtime data
 * and source, so the tables never drift from the code:
 *
 * - catalogue/hardcores.md     — the compiled hardcore list (HARDCORE_SERVICES)
 * - catalogue/exposures.md     — every hardcore mechanism exposure (descriptor manifests)
 * - catalogue/manifest.md      — the participant manifest surfaces and their keys
 * - catalogue/error-codes.md   — every stable error `code` and its class
 * - catalogue/observations.md  — every observation-stream event name and source
 *
 * It also replaces TypeDoc's path-based module titles in reference/ with
 * readable names. Run through `npm run docs:api`.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HARDCORE_SERVICES } from '../../../packages/kernel/src/bootstrap/hardcoreServices.js';
import { createEventsDescriptor } from '../../../packages/kernel/services/Events/index.js';
import { createInterceptionDescriptor } from '../../../packages/kernel/services/Interception/index.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const DOCS = join(HERE, '..');
const KERNEL = join(HERE, '../../../packages/kernel');
const OUT = join(DOCS, 'catalogue');
const BANNER = '<!-- Generated by docs/kernel-api/tools/generate-catalogue.ts. Do not edit by hand. -->\n\n';

/** Readable titles for the TypeDoc modules, keyed by the generated file. */
const MODULE_TITLES: Readonly<Record<string, string>> = {
  'src/contracts.md': 'Kernel contracts',
  'services/IdentityRegistry/contracts.md': 'Identity Registry (hardcore 1)',
  'services/ExposedApiRegistry/contracts.md': 'Exposed API Registry (hardcore 2)',
  'services/Parser/contracts.md': 'Parser (hardcore 3)',
  'services/Router/contracts.md': 'Router (hardcore 4)',
  'services/WasmCage.md': 'WASM Cage (hardcore 5)',
  'services/Events/contracts.md': 'Events (hardcore 6)',
  'services/Interception/contracts.md': 'Interception (hardcore 7)',
};

function sourceFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);

    if (statSync(full).isDirectory()) {
      return ['__tests__', '__verification__', 'node_modules', 'dist'].includes(name) ? [] : sourceFiles(full);
    }

    return name.endsWith('.ts') && !name.endsWith('.test.ts') && !name.endsWith('.d.ts') ? [full] : [];
  });
}

function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]): string => `| ${cells.join(' | ')} |`;

  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)].join('\n');
}

const code = (value: string): string => `\`${value}\``;
const files = [...sourceFiles(join(KERNEL, 'src')), ...sourceFiles(join(KERNEL, 'services'))];
const where = (file: string): string => code(relative(join(KERNEL, '..', '..'), file));

mkdirSync(OUT, { recursive: true });

// Hardcores.
writeFileSync(join(OUT, 'hardcores.md'), `${BANNER}# The seven hardcores\n\nThe compiled hardcore list, in boot order. Each hardcore is verified against its pinned content hash at boot; a \`mechanism\` hardcore is infrastructure and maps to non-official.\n\n${table(
  ['#', 'Token', 'Contract version', 'Contract interface', 'Mechanism'],
  HARDCORE_SERVICES.map((entry, index) => [
    String(index + 1),
    code(entry.token),
    entry.contractVersion,
    entry.contractInterface.map(code).join(', '),
    entry.mechanism === true ? 'yes' : 'no',
  ]),
)}\n`);

// Exposures.
const exposureRows = [createEventsDescriptor(), createInterceptionDescriptor()].flatMap((descriptor) =>
  (descriptor.manifest?.exposures ?? []).map((exposure) => [
    code(`${exposure.name}@${String(exposure.version ?? 1)}`),
    code(exposure.scope ?? 'kernel'),
    exposure.policy === undefined ? 'none' : code(JSON.stringify(exposure.policy)),
    code(descriptor.token.id),
  ]));

writeFileSync(join(OUT, 'exposures.md'), `${BANNER}# Mechanism exposures\n\nThe callable APIs the hardcores register with the exposed-API registry. A participant reaches each one with \`registry.resolve(name)\`; a caged participant reaches it through the cage's \`resolve\`. Scope: \`kernel\` admits kernel origin; \`runtime\` admits kernel and runtime; \`host\` admits host; \`any\` admits all.\n\n${table(['Exposure', 'Scope', 'Policy', 'Hardcore'], exposureRows)}\n`);

// Manifest surfaces.
const manifestSource = readFileSync(join(KERNEL, 'src/contracts/manifest.ts'), 'utf8');
const keySets = [...manifestSource.matchAll(/const (\w+)_KEYS = new Set\(\[([^\]]*)\]\)/gu)].map((match) => [
  code(match[1] ?? ''),
  (match[2] ?? '').split(',').map((key) => key.trim().replace(/'/gu, '')).filter(Boolean).map(code).join(', '),
]);

writeFileSync(join(OUT, 'manifest.md'), `${BANNER}# Participant manifest surfaces\n\nThe keys \`admitParticipantManifest\` accepts. Any other key is refused (\`PARTICIPANT_MANIFEST_INVALID\`). Types: see the Kernel contracts reference (\`ParticipantManifest\`, \`ExposureDeclaration\`, \`EventDeclaration\`, \`InterceptionDeclaration\`, \`InterceptionPointDeclaration\`).\n\n${table(['Key set', 'Accepted keys'], keySets)}\n`);

// Error codes.
const errorRows: string[][] = [];

for (const file of files) {
  const source = readFileSync(file, 'utf8');

  for (const match of source.matchAll(/export class (\w+)[^{]*\{([\s\S]*?)\n\}/gu)) {
    const found = /\bcode\s*=\s*'([A-Z][A-Z0-9_]+)'/u.exec(match[2] ?? '');

    if (found?.[1] !== undefined) {
      errorRows.push([code(found[1]), code(match[1] ?? ''), where(file)]);
    }
  }
}

errorRows.sort((left, right) => (left[0] ?? '').localeCompare(right[0] ?? ''));
writeFileSync(join(OUT, 'error-codes.md'), `${BANNER}# Error codes\n\nEvery stable, machine-readable \`code\` a kernel error class carries. Match on \`code\`, not on the message.\n\n${table(['Code', 'Class', 'Defined in'], errorRows)}\n`);

// Observations.
const observationRows = new Map<string, string[]>();
/** Token constants (`export const XToken = createServiceToken<…>('id')`) resolved to their ids. */
const tokenIds = new Map<string, string>();

for (const file of files) {
  for (const match of readFileSync(file, 'utf8').matchAll(/export const (\w+Token)\s*=\s*createServiceToken<[^>]*>\(\s*'([^']+)'/gu)) {
    tokenIds.set(`${match[1] ?? ''}.id`, match[2] ?? '');
  }
}

for (const file of files) {
  const source = readFileSync(file, 'utf8');
  const constant = /const OBSERVATION_SOURCE\s*=\s*([^;]+);/u.exec(source)?.[1]?.trim() ?? '';
  const sourceName = constant.startsWith("'") ? constant.replace(/'/gu, '') : (tokenIds.get(constant) ?? constant);
  const namespaces = new Set<string>();

  for (const match of source.matchAll(/(?:observe|#observe)\(\s*(?:(OBSERVATION_SOURCE|'[^']+')\s*,\s*)?'([a-z][\w.-]*)'/gu)) {
    const emitter = match[1] === undefined || match[1] === 'OBSERVATION_SOURCE' ? sourceName : match[1].replace(/'/gu, '');
    const event = match[2] ?? '';

    observationRows.set(`${emitter} ${event}`, [code(event), code(emitter || '(caller-supplied)'), where(file)]);
    namespaces.add(event.split('.')[0] ?? '');
  }

  // Event names passed through a typed parameter (e.g. `observation: 'a.b.c' | 'a.b.d'`).
  if (sourceName !== '') {
    for (const match of source.matchAll(/'([a-z]+(?:\.[a-z-]+){2,})'/gu)) {
      const event = match[1] ?? '';

      if (namespaces.has(event.split('.')[0] ?? '')) {
        observationRows.set(`${sourceName} ${event}`, [code(event), code(sourceName), where(file)]);
      }
    }
  }
}

writeFileSync(join(OUT, 'observations.md'), `${BANNER}# Observation-stream events\n\nEvents the kernel records on its observation stream (\`KernelCallAuthority.observe\`; read with \`BrudKernel.readObservations()\`). Diagnostics only — not a delivery mechanism.\n\n${table(['Event', 'Source', 'Recorded in'], [...observationRows.values()].sort((a, b) => (a[0] ?? '').localeCompare(b[0] ?? '')))}\n`);

// Readable module titles in the TypeDoc reference.
const reference = join(DOCS, 'reference');

for (const [file, title] of Object.entries(MODULE_TITLES)) {
  const path = join(reference, file);
  const text = readFileSync(path, 'utf8');

  writeFileSync(path, text.replace(/^# .+$/mu, `# ${title}`));
}

const index = join(reference, 'README.md');
let indexText = readFileSync(index, 'utf8');

for (const [file, title] of Object.entries(MODULE_TITLES)) {
  indexText = indexText.replace(new RegExp(`\\[[^\\]]+\\]\\(${file.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&')}\\)`, 'u'), `[${title}](${file})`);
}

writeFileSync(index, indexText);
console.log(`catalogue: ${String(HARDCORE_SERVICES.length)} hardcores, ${String(exposureRows.length)} exposures, ${String(keySets.length)} key sets, ${String(errorRows.length)} error codes, ${String(observationRows.size)} observation events`);
