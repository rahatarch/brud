#!/usr/bin/env bash
# Rebuilds packages/cli/runtime/quickjs.wasm and its pinned digest. Maintainers only:
# `brud pack` ships the committed binary and checks its digest, so nobody needs a
# C toolchain to use the CLI.
#
#   WASI_SDK=/path/to/wasi-sdk-34 QUICKJS=/path/to/quickjs-ng ./build.sh
#
# Needs: a wasi-sdk (clang + wasi-libc), a quickjs-ng checkout, node, and the
# `binaryen` npm package installed in the folder you run this from (npm i binaryen).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
cli="$here/../.."
: "${WASI_SDK:?set WASI_SDK}" "${QUICKJS:?set QUICKJS}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

node -e '
const fs = require("fs");
const bytes = fs.readFileSync(process.argv[1]);
const body = Array.from(bytes).concat(0).join(",");
fs.writeFileSync(process.argv[2], "static const char prelude_js[] = {" + body + "};\nstatic const unsigned int prelude_js_len = " + bytes.length + ";\n");
' "$here/prelude.js" "$work/prelude.h"

"$WASI_SDK/bin/clang" --target=wasm32-wasip1 --sysroot="$WASI_SDK/share/wasi-sysroot" -${OPT:-O2} -DNDEBUG -D_GNU_SOURCE \
  -D_WASI_EMULATED_SIGNAL -D_WASI_EMULATED_PROCESS_CLOCKS -I"$QUICKJS" -I"$work" \
  -mexec-model=reactor -Wl,--no-entry -Wl,--export=brud_alloc -Wl,--export=brud_invoke -Wl,--allow-undefined \
  -Wl,-z,stack-size=524288 -Wl,--initial-memory=8388608 \
  "$here/shim.c" "$QUICKJS/quickjs.c" "$QUICKJS/libregexp.c" "$QUICKJS/libunicode.c" "$QUICKJS/dtoa.c" \
  -lwasi-emulated-signal -lwasi-emulated-process-clocks -o "$work/qjs-wasi.wasm"

node "$here/stub-imports.mjs" "$work/qjs-wasi.wasm" "$cli/runtime/quickjs.wasm"

digest="$(sha256sum "$cli/runtime/quickjs.wasm" | cut -d' ' -f1)"
commit="$(git -C "$QUICKJS" rev-parse --short HEAD 2>/dev/null || echo unknown)"

cat > "$cli/src/commands/pack/javascript/runtimeInfo.ts" <<TS
/** Generated by runtime/quickjs/build.sh; do not edit. The pinned digest of runtime/quickjs.wasm. */
export const RUNTIME_SHA256 = '$digest';

/** Where the runtime came from, for provenance. */
export const RUNTIME_SOURCE = 'quickjs-ng $commit, $(basename "$WASI_SDK")';
TS

echo "runtime/quickjs.wasm sha256 $digest"
