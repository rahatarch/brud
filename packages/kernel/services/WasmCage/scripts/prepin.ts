// The cage's pre-pin hook, run by packages/kernel/scripts/repin.ts before the
// hardcore pins are computed. Regenerates src/nativeDigests.ts from the
// binaries in native/; with --check, fails if the table is stale.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const cage = join(dirname(fileURLToPath(import.meta.url)), '..');
const nativeDir = join(cage, 'native');
const table = join(cage, 'src/nativeDigests.ts');
const entries = readdirSync(nativeDir)
  .filter((name) => /^brud-wasm-cage\..+\.node$/u.test(name))
  .sort()
  .map((name) => {
    const key = name.slice('brud-wasm-cage.'.length, -'.node'.length);
    const digest = createHash('sha256').update(readFileSync(join(nativeDir, name))).digest('hex');

    return `  ['${key}', '${digest}'],`;
  });
const next = `/**
 * SHA-256 digests of the cage's native binaries, as \`[platform key, digest]\`.
 *
 * Generated by \`services/WasmCage/scripts/prepin.ts\` (run through the kernel's
 * \`npm run repin\`); do not edit by hand. The table is part of the cage's pinned
 * package graph, so the hardcore content pins cover it; the loader refuses any
 * binary whose digest is not listed here.
 */
export const WASM_CAGE_NATIVE_DIGESTS: readonly (readonly [string, string])[] = Object.freeze([
${entries.join('\n')}
]);
`;

if (readFileSync(table, 'utf8') !== next) {
  if (process.argv.includes('--check')) {
    console.error('native digests: stale');
    process.exit(1);
  }

  writeFileSync(table, next, 'utf8');
  console.log('native digests: updated');
}
